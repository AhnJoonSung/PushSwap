#include "libft.h"
#include <stdlib.h>

t_list	*ft_lstnew(int content)
{
	t_list	*node;

	node = (t_list *)malloc(sizeof(t_list));
	if (!node)
		exit(EXIT_FAILURE);
	node->content = content;
	node->next = 0;
	node->prv = 0;
	return (node);
}
